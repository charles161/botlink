/** Estimated width in px; 3% over the measured advances so the layout check errs on the safe side. */
export function textWidth(s, size, weight = 400) {
  const t = WIDTH[weight];
  let u = 0;
  for (const ch of s) u += t.get(ch) ?? 1038;
  return (u / 1000) * size * 1.03;
}
/** Greedy word wrap to `max` px. A word longer than the line stays whole (the check then reports the overflow). */
export function wrap(s, max, size, weight = 400) {
  const words = String(s).split(/\s+/).filter(Boolean);
  const lines = [];
  let cur = "";
  for (const w of words) {
    const next = cur ? `${cur} ${w}` : w;
    if (!cur || textWidth(next, size, weight) <= max) cur = next;
    else {
      lines.push(cur);
      cur = w;
    }
  }
  if (cur) lines.push(cur);
  return lines;
}

