const rx = (s) => new RegExp(s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));

/** Every source of every box, arrow, message and note: what it proves, and whether it still matches. */
export function sourceProblems(d, root) {
  const R = new Reader(root);
  const out = [], skipped = [], notCheckable = [];
  const check = (what, sources) => {
    if (!Array.isArray(sources) || !sources.length) {
      out.push(`${DATA}: ${what} has no source: name the file and text (or the test) that shows it`);
      return;
    }
    let tested = 0;
    for (const s of sources) {
      const top = s.file.split("/")[0];
      // left out of this copy: the folder is missing, or the public export dropped the file (.public-export)
      if ((PRIVATE_DIRS.includes(top) && !existsSync(join(root, top))) || (!existsSync(join(root, s.file)) && omitted(root, s.file))) {
        skipped.push(`${what}: ${s.file}`);
        continue;
      }
      tested++;
      const re = s.test ? testRe(s.file, s.test) : s.re ? new RegExp(s.re, s.flags || "") : typeof s.text === "string" ? rx(s.text) : null;
      if (!re) {
        out.push(`${DATA}: ${what}: a source in ${s.file} has no text, re or test`);
        continue;
      }
      try {
        R.at(what, s.file, re);
      } catch (e) {
        const how = s.test ? `the test "${s.test}" is gone` : `${JSON.stringify(s.text ?? s.re)} is no longer there`;
        out.push(`${DATA}: ${what} rests on ${s.file}, and ${how}. Check the code: if it changed, change the diagram (the box, the arrow or its source) and run node docs/architecture/render.mjs`);
      }
    }
    if (!tested) notCheckable.push(`not checkable here: ${what}: its sources ship only in the private tree (${[...new Set(sources.map((s) => s.file))].join(", ")})`);
  };
  const C = d.component;
  const ids = new Set();
  for (const c of C.components) {
    if (ids.has(c.id)) out.push(`${DATA}: the id "${c.id}" is used twice`);
    ids.add(c.id);
    if (c.group && !C.groups.some((g) => g.id === c.group)) out.push(`${DATA}: the box "${c.label}" sits in a group "${c.group}" that does not exist`);
    check(`the box "${c.label}"`, c.sources);
  }
  for (const k of C.connectors) {
    const what = `the arrow "${nameOf(C.components, k.from)} → ${nameOf(C.components, k.to)}" (${k.label || "no label"})`;
    if (!ids.has(k.from) || !ids.has(k.to)) out.push(`${DATA}: ${what} names a box that does not exist`);
    if (!k.label || !k.label.trim()) out.push(`${DATA}: ${what} has no label: every arrow says what travels on it`);
    if (!k.mechanism) out.push(`${DATA}: ${what} has no mechanism (the protocol or the way it travels)`);
    check(what, k.sources);
  }
  const S = d.sequence;
  const pids = new Set(S.participants.map((q) => q.id));
  sequenceMessages(S).forEach((m, i) => {
    const what = `message ${i + 1} of the join ("${m.label || "no label"}")`;
    if (!pids.has(m.from) || !pids.has(m.to)) out.push(`${DATA}: ${what} names a participant that does not exist`);
    if (!m.label || !m.label.trim()) out.push(`${DATA}: ${what} has no label`);
    if (!["sync", "async", "return", "self"].includes(m.kind)) out.push(`${DATA}: ${what} has kind "${m.kind}" (sync, async, return or self)`);
    if ((m.kind === "self") !== (m.from === m.to)) out.push(`${DATA}: ${what}: a self message goes from a participant to itself, and only then`);
    check(what, m.sources);
  });
  for (const n of C.notes || []) {
    const what = `the note on "${nameOf(C.components, n.attach)}" ("${String(n.text).slice(0, 50)}…")`;
    if (!ids.has(n.attach)) out.push(`${DATA}: ${what} is attached to a box that does not exist`);
    check(what, n.sources);
  }
  for (const [i, x] of (d.notes || []).entries()) check(`caption sentence ${i + 1} ("${x.text.slice(0, 50)}…")`, x.sources);
  // absolute words: every one in a label is on the reviewed list with the exact words, why they are true and a source
  const listed = d.absolutes || [];
  const used = new Set();
  for (const [where, t] of wordsOf(d)) {
    for (const m of String(t).matchAll(ABSOLUTE)) {
      const hit = listed.findIndex((a) => t.includes(a.text) && new RegExp(`\\b${m[0]}\\b`, "i").test(a.text));
      if (hit < 0) out.push(`${DATA}: ${where} says "${m[0]}" ("${t}"): check it against the code, then list the exact words under "absolutes" with why they are true and a source, or say it without the absolute word`);
      else used.add(hit);
    }
  }
  listed.forEach((a, i) => {
    if (!used.has(i)) out.push(`${DATA}: the reviewed absolute "${a.text}" is no longer in any label: remove it from "absolutes"`);
    if (!a.why) out.push(`${DATA}: the reviewed absolute "${a.text}" has no "why"`);
    check(`the absolute "${a.text}"`, a.sources);
  });
  return { out, skipped, notCheckable };
}

// Words that claim more than a snippet usually shows. Each use in a label needs a reviewed entry under "absolutes".
export const ABSOLUTE = /\b(cannot|can't|never|always|only|all|every)\b/gi;
/** Every text a reader sees, with where it is: box names and lines, arrow labels, notes, messages, guards, captions, legend. */
export function wordsOf(d) {
  const C = d.component, out = [];
  for (const c of C.components) for (const t of [c.label, ...(c.sub || [])]) out.push([`the box "${c.label}"`, t]);
  for (const g of C.groups) out.push([`the group "${g.label}"`, g.label]);
  for (const k of C.connectors) out.push([`the arrow "${nameOf(C.components, k.from)} → ${nameOf(C.components, k.to)}"`, k.label]);
  for (const n of C.notes || []) out.push([`the note on "${nameOf(C.components, n.attach)}"`, n.text]);
  for (const it of C.legend?.items || []) out.push(["the legend", it.text]);
  sequenceMessages(d.sequence).forEach((m, i) => {
    out.push([`message ${i + 1} of the join`, m.label]);
    if (m.first) out.push([`the guard of message ${i + 1}`, m.guard]);
  });
  for (const x of d.notes || []) out.push(["a caption sentence", x.text]);
  out.push(["the check sentence of the caption", CHECK_SENTENCE]);
  out.push(["the sequence caption", captions(d).sequence]);
  return out;
}

/** Arrows start and end on the boxes they name. */
function endpointProblems(d) {
  const out = [];
  const C = d.component;
  const box = Object.fromEntries(C.components.map((c) => [c.id, c.at]));
  for (const k of C.connectors) {
    const what = `the arrow "${nameOf(C.components, k.from)} → ${nameOf(C.components, k.to)}"`;
    if (!Array.isArray(k.route) || k.route.length < 2) {
      out.push(`${DATA}: ${what} has no route`);
      continue;
    }
    if (box[k.from] && !onEdge(k.route[0], box[k.from])) out.push(`${DATA}: ${what} does not start on the edge of "${nameOf(C.components, k.from)}" (route starts at ${k.route[0]})`);
    if (box[k.to] && !onEdge(k.route[k.route.length - 1], box[k.to])) out.push(`${DATA}: ${what} does not end on the edge of "${nameOf(C.components, k.to)}" (route ends at ${k.route[k.route.length - 1]})`);
    for (let i = 0; i + 1 < k.route.length; i++) {
      const [a, b] = [k.route[i], k.route[i + 1]];
      if (a[0] !== b[0] && a[1] !== b[1]) out.push(`${DATA}: ${what} has a slanted segment (${a} to ${b}); keep arrows to straight runs and right angles`);
    }
  }
  for (const n of C.notes || []) {
    const what = `the note on "${nameOf(C.components, n.attach)}"`;
    if (!Array.isArray(n.link) || n.link.length < 2) out.push(`${DATA}: ${what} has no line to its box`);
    else {
      if (!onEdge(n.link[0], n.at)) out.push(`${DATA}: the line of ${what} does not start on the note's edge (${n.link[0]})`);
      if (box[n.attach] && !onEdge(n.link[n.link.length - 1], box[n.attach])) out.push(`${DATA}: the line of ${what} does not end on the edge of "${nameOf(C.components, n.attach)}" (${n.link[n.link.length - 1]})`);
    }
  }
  return out;
}

/** Width and height of a PNG, and its text chunks. */
export function pngInfo(buf) {
  if (buf.length < 33 || buf.toString("latin1", 1, 4) !== "PNG") return null;
  const info = { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20), text: {} };
  let o = 8;
  while (o + 8 <= buf.length) {
    const len = buf.readUInt32BE(o), type = buf.toString("latin1", o + 4, o + 8);
    if (type === "tEXt") {
      const data = buf.subarray(o + 8, o + 8 + len);
      const z = data.indexOf(0);
      info.text[data.toString("latin1", 0, z)] = data.toString("latin1", z + 1);
    }
    if (type === "IEND") break;
    o += 12 + len;
  }
  return info;
}

export function build(root) {
  const d = load(root);
  const files = {};
  const scenes = [];
  for (const theme of ["light", "dark"]) {
    const a = componentSVG(d, theme);
    files[SVGS[`architecture-${theme}`]] = a.svg;
    scenes.push(a);
    const s = sequenceSVG(d, theme);
    files[SVGS[`join-sequence-${theme}`]] = s.svg;
    scenes.push(s);
  }
  files[EMBED] = embedBlock(d) ;
  return { d, files, scenes };
}

/** For web/scripts/check.mjs: what this copy of the repository cannot check, said out loud (never a quiet skip). */
export function diagramWarnings(root = resolve(HERE, "../..")) {
  try {
    const { skipped, notCheckable } = sourceProblems(load(root), root);
    if (!skipped.length) return [];
    return [`architecture diagram: ${skipped.length} sources sit in folders this copy leaves out; ${notCheckable.length === 1 ? "1 claim has" : `${notCheckable.length} claims have`} no checkable source here (drawn with \u2020):`, ...notCheckable.map((x) => `  ${x}`)];
  } catch {
    return [];
  }
}

/** For web/scripts/check.mjs: every problem, or []. */
export function diagramProblems(root = resolve(HERE, "../..")) {
  let built;
  try {
    built = build(root);
  } catch (e) {
    return [`architecture diagram: ${e.message}`];
  }
  const { d, files, scenes } = built;
  const out = [];
  out.push(...sourceProblems(d, root).out);
  out.push(...endpointProblems(d));
  out.push(...colourProblems());
  // the light scenes carry the same layout as the dark ones: check one of each
  for (const s of [scenes[0], scenes[1]]) out.push(...layoutProblems(s.sc, s.W, s.H));
  for (const [f, text] of Object.entries(files)) {
    const p = join(root, f);
    const now = existsSync(p) ? readFileSync(p, "utf8") : null;
    if (now !== text) out.push(`${f}: ${now === null ? "missing" : "differs from what docs/architecture/render.mjs draws from the data"}. Run: node docs/architecture/render.mjs (then look at the PNGs: python3 docs/architecture/png.py)`);
  }
  for (const f of Object.values(SVGS)) {
    const pf = join(root, png(f));
    if (!existsSync(pf)) {
      out.push(`${png(f)}: missing. Run: python3 docs/architecture/png.py`);
      continue;
    }
    const info = pngInfo(readFileSync(pf));
    const svg = files[f];
    const [, w, h] = /width="(\d+)" height="(\d+)"/.exec(svg) || [];
    const sha = createHash("sha256").update(svg).digest("hex");
    if (!info) out.push(`${png(f)}: not a PNG. Run: python3 docs/architecture/png.py`);
    else if (info.text[PNG_KEY] !== sha) out.push(`${png(f)}: was not drawn from the current ${f}. Run: python3 docs/architecture/png.py`);
    else if (info.w !== 2 * Number(w) || info.h !== 2 * Number(h)) out.push(`${png(f)}: is ${info.w}x${info.h}; the 2x render of ${f} is ${2 * w}x${2 * h}. Run: python3 docs/architecture/png.py`);
  }
  const block = files[EMBED];
  for (const rm of READMES) {
    const p = join(root, rm);
    if (!existsSync(p)) continue;
    const t = readFileSync(p, "utf8");
    const a = t.indexOf(START), b = t.indexOf(END);
    if (a < 0 && /docs\/img\/(architecture|join-sequence)-/.test(t)) out.push(`${rm}: shows the diagrams without the generated block: paste ${EMBED} instead`);
    if (a >= 0 && (b < a || t.slice(a, b + END.length) + "\n" !== block)) out.push(`${rm}: its architecture block differs from ${EMBED}: paste ${EMBED} again`);
    if (a < 0 && REQUIRE_README_EMBED && rm === READMES[1]) out.push(`${rm}: the architecture block is missing: paste ${EMBED}`);
  }
  return [...new Set(out)];
}

