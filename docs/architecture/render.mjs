// a box in words: its name, then its lines as one phrase (a wrapped line continues the one before it)
const label = (c) => {
  const sub = (c.sub || []).reduce((acc, l) => (!acc ? l : /[,:;.]$/.test(acc) || /^[a-z~]/.test(l) ? `${acc} ${l}` : `${acc}; ${l}`), "");
  return sub ? `${c.label} (${sub})` : c.label;
};
const nameOf = (comps, id) => comps.find((c) => c.id === id)?.label ?? id;

function onEdge(pt, at) {
  const [x, y, w, h] = at;
  const [px, py] = pt;
  const inX = px >= x - 0.5 && px <= x + w + 0.5, inY = py >= y - 0.5 && py <= y + h + 0.5;
  return (inX && (Math.abs(py - y) <= 0.5 || Math.abs(py - (y + h)) <= 0.5)) || (inY && (Math.abs(px - x) <= 0.5 || Math.abs(px - (x + w)) <= 0.5));
}

function arrowHead(sc, pts, colour, what, open = true) {
  const [a, b] = [pts[pts.length - 2], pts[pts.length - 1]];
  const ang = Math.atan2(b[1] - a[1], b[0] - a[0]);
  const L = 13, s = 0.42;
  const p1 = [b[0] - L * Math.cos(ang - s), b[1] - L * Math.sin(ang - s)];
  const p2 = [b[0] - L * Math.cos(ang + s), b[1] - L * Math.sin(ang + s)];
  sc.seg(p1, b, what);
  sc.seg(p2, b, what);
  if (open) sc.out.push(`<path d="M${r1(p1[0])} ${r1(p1[1])} L${r1(b[0])} ${r1(b[1])} L${r1(p2[0])} ${r1(p2[1])}" fill="none" stroke="${colour}" stroke-width="1.75"/>`);
  else sc.out.push(`<path d="M${r1(p1[0])} ${r1(p1[1])} L${r1(b[0])} ${r1(b[1])} L${r1(p2[0])} ${r1(p2[1])} Z" fill="${colour}" stroke="${colour}" stroke-width="1.5"/>`);
}

