// Downloads the three self-hosted font families (latin subset, woff2) from Google Fonts
// and writes web/public/assets/fonts/*.woff2 + fonts.css. The page CSP is default-src 'self',
// so fonts must be served from our own origin. Re-run only when changing fonts:
//   node web/scripts/fetch-fonts.mjs
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "public", "assets", "fonts");
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
const families = [
  { css: "Fraunces:opsz,wght@9..144,400..700", file: "fraunces", family: "Fraunces" },
  { css: "Fraunces:ital,opsz,wght@1,9..144,400..700", file: "fraunces-italic", family: "Fraunces" },
  { css: "Figtree:wght@400..800", file: "figtree", family: "Figtree" },
  { css: "JetBrains+Mono:wght@500..700", file: "jetbrains-mono", family: "JetBrains Mono" },
];

await mkdir(out, { recursive: true });
let css = "/* generated by web/scripts/fetch-fonts.mjs — latin subset, self-hosted (CSP default-src 'self') */\n";
for (const f of families) {
  const res = await fetch(`https://fonts.googleapis.com/css2?family=${f.css}&display=swap`, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${f.css}: ${res.status}`);
  const text = await res.text();
  // Keep only the /* latin */ block.
  const blocks = text.split("/* ").filter((b) => b.startsWith("latin */"));
  if (!blocks.length) throw new Error(`no latin block for ${f.css}`);
  const block = blocks[0];
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const bytes = Buffer.from(await (await fetch(url, { headers: { "User-Agent": UA } })).arrayBuffer());
  await writeFile(join(out, `${f.file}.woff2`), bytes);
  const style = (block.match(/font-style:\s*(\w+)/) || [, "normal"])[1];
  const weight = block.match(/font-weight:\s*([\d ]+)/)[1].trim();
  const range = block.match(/unicode-range:\s*([^;]+);/)[1];
  css += `@font-face{font-family:"${f.family}";font-style:${style};font-weight:${weight};font-display:swap;src:url(/assets/fonts/${f.file}.woff2) format("woff2");unicode-range:${range}}\n`;
  console.log(`${f.file}.woff2 ${bytes.length} bytes`);
}
await writeFile(join(out, "fonts.css"), css);
