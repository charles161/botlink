const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
/** h("p", {class: "x"}, "text", h(...)): text children are escaped; children made by h are kept as they are. */
class Html { constructor(s) { this.s = s; } toString() { return this.s; } }
function h(tag, attrs, ...kids) {
  const a = Object.entries(attrs || {}).filter(([, v]) => v !== null && v !== undefined && v !== false).map(([k, v]) => (v === true ? ` ${k}` : ` ${k}="${esc(v)}"`)).join("");
  const inner = kids.flat(Infinity).filter((k) => k !== null && k !== undefined && k !== false).map((k) => (k instanceof Html ? k.s : esc(k))).join("");
  return new Html(`<${tag}${a}>${inner}</${tag}>`);
}
