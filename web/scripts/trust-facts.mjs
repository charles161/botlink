/** A test that must exist by name: Go `func Name(`, node `test("Name"`, Python `def name(`. */
export const testRe = (file, name) => {
  const q = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  if (file.endsWith(".go")) return new RegExp(`^func ${q}\\(t \\*testing\\.T\\)`, "m");
  if (file.endsWith(".py")) return new RegExp(`^def ${q}\\(`, "m");
  return new RegExp(`^test\\("${q}",`, "m");
};

// Batch approval (SPEC §6.4 step 7a): one passkey step can let in up to humancheck.MaxTargets waiting chats of one room.
// While that is more than one, a public page that says each join asks for the passkey is false: the passkey is asked
// at each approval. (17 Nov 2026: the landing said "Each join asks for the passkey again" after batch approval shipped.)
export const PER_JOIN_PAGES = ["web/public/security.html", "web/public/trust.html", "web/public/assets/landing-claims.json"];
const PER_JOIN = [
  /\beach join\b[^.]{0,80}\bpasskey\b/i,
  /\bpasskey\b[^.]{0,80}\b(?:each|every|per|for each) join\b/i,
  /\bper join\b/i,
  /\bapprov\w*\b[^.]{0,60}\bpasskey\b[^.]{0,30}\beach time\b/i,
];
const NUMBER_WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"];
/** "up to five": how the pages write the batch cap (a number word up to ten, else digits). */
export const capWords = (n) => NUMBER_WORDS[n] ?? String(n);
/** The cap on chats one approval lets in, read from the server's code. */
export const readMaxTargets = (text) => {
  const m = /const MaxTargets = (\d+)/.exec(text);
  if (!m) throw new Error("server/internal/humancheck/humancheck.go: const MaxTargets is no longer found (the batch cap the pages name)");
  return Number(m[1]);
};
/** The pieces of text a person reads on a page, one per cell, list item, paragraph or claim field. */
function readPieces(rel, src) {
  if (rel.endsWith(".json")) {
    const d = JSON.parse(src), out = [];
    for (const c of [d?.hero, ...(Array.isArray(d?.steps) ? d.steps : []), d?.note].filter(Boolean)) for (const k of ["title", "short", "text", "caveat"]) if (typeof c[k] === "string") out.push(c[k]);
    return out;
  }
  return src.replace(/<!--[\s\S]*?-->/g, " ").replace(/<(script|style)\b[\s\S]*?<\/\1>/gi, " ").replace(/\s+/g, " ")
    .replace(/<\/(p|li|td|th|tr|h[1-6]|summary|dt|dd|div|caption)>|<br\s*\/?>/gi, "\n").replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&").replace(/&quot;/g, '"').split("\n").map((s) => s.replace(/\s+/g, " ").trim()).filter(Boolean);
}
/**
 * What is wrong with the pages' join-approval wording, given the cap: [] when it is right. texts: {rel: file text}.
 * With a cap above one, no piece may say the passkey is asked per join, and the security page must name the cap.
 */
export function perJoinProblems(maxTargets, texts) {
  const out = [];
  if (!(maxTargets > 1)) return out;
  for (const [rel, src] of Object.entries(texts)) {
    if (typeof src !== "string") continue;
    for (const s of readPieces(rel, src)) {
      const re = PER_JOIN.find((r) => r.test(s));
      if (re) out.push(`${rel}: ${JSON.stringify(s.length > 160 ? s.slice(0, 157) + "…" : s)} says the passkey is asked for each join, but one approval lets in up to ${maxTargets} chats (MaxTargets in server/internal/humancheck/humancheck.go): say "each approval asks for the passkey" and name the cap`);
      for (const m of s.matchAll(/\b(?:up to|at most) (\w+) (?:waiting |ticked )+chats\b/gi)) {
        if (m[1].toLowerCase() !== capWords(maxTargets) && m[1] !== String(maxTargets)) out.push(`${rel}: "${m[0]}" names a batch cap of ${m[1]}, but the code's is ${maxTargets} (MaxTargets in server/internal/humancheck/humancheck.go)`);
      }
    }
  }
  const sec = texts["web/public/security.html"];
  const cap = `up to ${capWords(maxTargets)} waiting chats`;
  if (typeof sec === "string" && !readPieces("web/public/security.html", sec).some((s) => s.includes(cap))) out.push(`web/public/security.html: does not say "${cap}" (one approval lets in up to ${maxTargets}: MaxTargets in server/internal/humancheck/humancheck.go)`);
  return out;
}

