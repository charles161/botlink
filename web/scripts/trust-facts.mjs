// ------------------------------------------------------------------ reading the code
export class Reader {
  constructor(root) {
    this.root = root;
    this.cache = new Map();
    this.sources = []; // {fact, file, line}
    this.inputs = new Set();
    this.skipped = []; // parts not re-read because the public export leaves their files out (export-omit.mjs)
  }
  text(file) {
    if (!this.cache.has(file)) {
      const p = join(this.root, file);
      if (!existsSync(p)) throw new Error(`${file}: not found`);
      this.cache.set(file, readFileSync(p, "utf8"));
      this.inputs.add(file);
    }
    return this.cache.get(file);
  }
  /** The first match of `re` in `file` (the match, and the line it starts on). Records the source under `fact`. */
  at(fact, file, re) {
    const t = this.text(file);
    const m = re.exec(t);
    if (!m) throw new Error(`${fact}: no longer found in ${file} (pattern ${re})`);
    const line = t.slice(0, m.index).split("\n").length;
    this.sources.push({ fact, file, line });
    return m;
  }
  ls(dir) {
    return readdirSync(join(this.root, dir)).sort();
  }
}

