//
//   node web/scripts/trust-facts.mjs            read the code, write web/public/assets/trust-facts.json and stamp the
//                                               page between its trust-facts markers
//   node web/scripts/trust-facts.mjs --check    exit 1 when the committed page or facts differ from what the code says
//                                               now (web/scripts/check.mjs runs this)
//   node web/scripts/trust-facts.mjs --refresh-results
//                                               also cite the newest results under evals/results/ (a change under
//                                               web/public only; run it after a gate run recorded new results)
//
// Eval results are checked for validity, not freshness: a result the page cites must still be recorded in
// evals/results/ with that commit, date and outcome, and a scenario the page shows with no run must have had no run
// recorded up to the date the page names. A newer result file therefore never fails the check (the deploy gate needs
// that: recording a result must not change the code it describes); a changed or deleted cited result does.
//   node web/scripts/trust-facts.mjs --sources  print every fact with the file:line it was read from
//   node web/scripts/trust-facts.mjs --inputs   print the files it reads (tests copy them)
//   --root <dir>                                read another copy of the repository (tests)
//
// Every fact is found by a pattern in a named file. A pattern that no longer matches is an error: the page would
// claim something nobody can point at any more. The page names the file of each fact; line numbers are printed by
// --sources only, so an edit above a fact does not break the build, a changed fact does.
// No framework and no innerHTML: the HTML is built here as text, with every value escaped.
