// Build-time: turn the self-hosted app icons (web/public/assets/apps/*.svg) into
//   1. web/public/assets/js/app-icons.js  path data for the inline "bot" badges (crisp, CSP-clean, no requests)
//   2. the app-colors block in web/public/assets/app.css  shell colours derived from each icon's dominant colour
//   node web/scripts/app-icons.mjs        (output is committed; re-run after changing an icon)
//
// Dominant colour: the area-agnostic average of the icon's paint (solid fills, gradient stops), ignoring white
// background plates. The bot body is that hue, moved into a friendly lightness band (light theme 0.66..0.78,
// dark theme 0.56..0.68) so the dark outline and eyes always read; achromatic logos get a soft neutral body.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const APPS = resolve(WEB, "public/assets/apps");
const OUT_JS = resolve(WEB, "public/assets/js/app-icons.js");
const CSS = resolve(WEB, "public/assets/app.css");

// key = the roster `app` value. viewBox crops a white plate off (Codex's icon is a glyph on a white tile).
const ICONS = [
  { key: "claude-code", file: "claude-code.svg" },
  { key: "codex", file: "codex.svg", viewBox: "2.6 2.6 18.8 18.8" },
  { key: "cursor", file: "cursor.svg" },
];

const attr = (tag, name) => (tag.match(new RegExp(`\\s${name}="([^"]*)"`)) || [])[1];
const hex2rgb = (h) => { h = h.replace("#", ""); if (h.length === 3) h = [...h].map((c) => c + c).join(""); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255); };
const isWhite = (h) => hex2rgb(h).every((v) => v > 0.97);
function rgb2hsl([r, g, b]) {
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2, d = mx - mn;
  if (!d) return [0, 0, l];
  const s = d / (1 - Math.abs(2 * l - 1));
  const h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [(h * 60 + 360) % 360, s, l];
}
function hsl2hex([h, s, l]) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return "#" + [r, g, b].map((v) => Math.round((v + m) * 255).toString(16).padStart(2, "0")).join("");
}
const clamp = (v, a, b) => Math.min(b, Math.max(a, v));

function parse(svg, viewBoxOverride) {
  const viewBox = viewBoxOverride || attr(svg.match(/<svg[^>]*>/)[0], "viewBox");
  const stops = [...svg.matchAll(/<stop[^>]*>/g)].map((m) => ({ offset: Number(attr(m[0], "offset") || 0), color: attr(m[0], "stop-color") }));
  const paths = [];
  const paints = [];
  for (const m of svg.matchAll(/<path[^>]*>/g)) {
    const t = m[0];
    const fill = attr(t, "fill") || "#000000";
    if (/^#/.test(fill) && isWhite(fill)) continue; // background plate
    const p = { d: attr(t, "d") };
    const rule = attr(t, "fill-rule") || attr(t, "clip-rule");
    if (rule === "evenodd") p.rule = "evenodd";
    if (/^url\(/.test(fill)) { p.fill = "gradient"; paints.push(...stops.map((s) => s.color)); }
    else { p.fill = fill.toUpperCase(); paints.push(fill); }
    paths.push(p);
  }
  return { viewBox, paths, gradient: stops.length ? stops : null, paints };
}

function colours(paints) {
  const rgbs = paints.map(hex2rgb);
  const avg = [0, 1, 2].map((i) => rgbs.reduce((a, c) => a + c[i], 0) / rgbs.length);
  const dominant = hsl2hex(rgb2hsl(avg));
  const [h, s, l] = rgb2hsl(avg);
  const neutral = s < 0.12; // black / grey logo: soft cool neutral body
  const body = neutral ? hsl2hex([210, 0.1, 0.8]) : hsl2hex([h, clamp(s, 0.45, 0.9), clamp(l, 0.66, 0.78)]);
  const bodyDark = neutral ? hsl2hex([210, 0.09, 0.66]) : hsl2hex([h, clamp(s, 0.4, 0.8), clamp(l, 0.56, 0.68)]);
  // a soft tint behind the badge rim + the arrival glow
  const tint = neutral ? hsl2hex([210, 0.12, 0.93]) : hsl2hex([h, clamp(s, 0.5, 0.9), 0.93]);
  return { dominant, body, bodyDark, tint };
}

const out = {};
for (const ic of ICONS) {
  const svg = await readFile(resolve(APPS, ic.file), "utf8");
  const p = parse(svg, ic.viewBox);
  out[ic.key] = { viewBox: p.viewBox, paths: p.paths, gradient: p.gradient, ...colours(p.paints) };
}

const js = `// GENERATED by web/scripts/app-icons.mjs from web/public/assets/apps/*.svg (see apps/SOURCES.md). Don't edit.
// Each app's original mark (path data) + colours derived from its dominant colour, for the bot badges in art.js.
export const APP_ICONS = ${JSON.stringify(out, null, 1)};
`;
await writeFile(OUT_JS, js);

const rules = ICONS.map(({ key }) => {
  const c = out[key];
  return `.char-${key} { --c: ${c.body}; --c-logo: ${c.dominant}; --c-tint: ${c.tint}; }`;
});
const dark = ICONS.map(({ key }) => `.char-${key} { --c: ${out[key].bodyDark}; }`);
const block = `/* app-colors:begin (generated by web/scripts/app-icons.mjs; bodies from each icon's dominant colour) */
${rules.join("\n")}
@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) ${dark.join(" :root:not([data-theme=\"light\"]) ")} }
${dark.map((r) => `:root[data-theme="dark"] ${r}`).join("\n")}
/* app-colors:end */`;
let css = await readFile(CSS, "utf8");
const re = /\/\* app-colors:begin[\s\S]*?app-colors:end \*\//;
if (!re.test(css)) throw new Error("app.css has no app-colors block (add /* app-colors:begin */ /* app-colors:end */ markers)");
css = css.replace(re, block);
await writeFile(CSS, css);
for (const [k, c] of Object.entries(out)) console.log(`${k.padEnd(12)} dominant ${c.dominant}  body ${c.body}  dark ${c.bodyDark}  tint ${c.tint}`);
